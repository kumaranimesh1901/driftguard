def _drift_type_pill(value: bool | None) -> str:
    if value is None:
        return status_pill("Unknown – labels pending", "unknown", dot=False)
    if value:
        return status_pill("Yes", "critical", dot=False)
    return status_pill("No", "low", dot=False)


def render() -> None:
    with st.spinner("Loading overview telemetry…"):
        data = safe(lambda: api.get("/overview"), retry_key="overview")
    if data is None:
        page_header(
            "Credit Model Surveillance Overview",
            "Continuous surveillance of loan applicants: 2020 baseline vs production batches",
            show_batch_selector=False,
        )
        return

    synthetic_pill = (
        status_pill(
            "Synthetic data",
            "neutral",
            dot=False,
            tooltip="Some or all records shown were generated by DriftGuard's simulator and are not real banking customers.",
        )
        if data.get("any_synthetic")
        else ""
    )
    page_header(
        "Credit Model Surveillance Overview",
        "2020 training baseline vs production credit batches · drift magnitude, model impact & performance",
        show_batch_selector=True,
        badge_html=synthetic_pill,
    )

    if not data["baseline"]:
        empty_state(
            "NO BASELINE",
            "No historical baseline registered yet",
            "Upload the 2020 baseline in Dataset Management"
            + (" or generate the synthetic demo dataset there." if is_admin() else "."),
        )
        return

    all_batches = safe(lambda: api.get("/batches"), []) or []
    batches = visible_batches(all_batches)
    hidden_count = len(all_batches) - len(batches)
    visible_ids = {b["batch_id"] for b in batches}

    analysed_batches = [b for b in batches if b.get("latest_analysis")]
    hero_meta = latest_batch(analysed_batches) or latest_batch(batches)
    hero_report = (
        safe(lambda: api.get(f"/analysis/latest/{hero_meta['batch_id']}"))
        if hero_meta and hero_meta.get("latest_job_id")
        else None
    )

    models = safe(lambda: api.get("/models"), []) or []
    champ = next((m for m in models if m.get("status") == "champion"), models[-1] if models else None)
    audit = safe(lambda: api.get("/audit-logs", {"limit": 50}), {}) or {}
    recent_alerts = [
        j
        for j in audit.get("jobs", [])
        if j.get("alert_type") and not (hide_test_batches() and is_test_batch(j.get("batch_id")))
    ]

    trend = [t for t in data.get("trend", []) if t["batch_id"] in visible_ids]
    trend.sort(key=lambda t: (t.get("batch_date") or "", t.get("batch_id") or ""))
    thresholds = _thresholds(data)

    # 1. Hero Row (2/3 single-batch status card + 1/3 drift-types panel)
    if hero_report:
        hero_bid = hero_report["batch_id"]
        hero_date = format_date(hero_report.get("batch_date") or (hero_meta or {}).get("batch_date"))
        risk = hero_report.get("risk_category") or "LOW RISK"
        accent_fg, _ = theme.risk_color(risk)
        hero_perf = hero_report.get("performance_state") or "unknown"
        hero_has_labels = bool((hero_report.get("model_health") or {}).get("has_production_labels"))
        dt = hero_report.get("drift_types") or {}

        older_confirmed_html = ""
        if not hero_has_labels:
            labelled_visible = [
                b
                for b in sorted(
                    analysed_batches,
                    key=lambda x: (x.get("batch_date") or "", x.get("uploaded_at") or ""),
                )
                if (b.get("labelled_rows") or 0) > 0
                and (b.get("latest_analysis") or {}).get("performance_state")
                not in (None, "unknown", "unconfirmed")
            ]
            if labelled_visible:
                prev = labelled_visible[-1]
                prev_state = (prev["latest_analysis"]["performance_state"] or "unknown").upper()
                older_confirmed_html = (
                    f'<div style="font-size:12px;color:{theme.MUTED};margin-top:8px;">'
                    f"Last confirmed performance: <b>{prev_state}</b> ({prev['batch_id']}, {format_date(prev.get('batch_date'))})</div>"
                )

        hero_left, hero_right = st.columns([2, 1])
        with hero_left:
            st.markdown(
                f"""
                <div class="dg-card" style="border-left:4px solid {accent_fg};height:100%;margin-bottom:0;">
                    <div style="font-size:12px;font-weight:600;text-transform:uppercase;letter-spacing:0.04em;color:{theme.MUTED};">
                        Latest Batch · {hero_bid} ({hero_date})
                    </div>
                    <div style="display:flex;align-items:center;gap:12px;margin-top:10px;flex-wrap:wrap;">
                        {risk_badge(risk)}
                        <span style="font-size:24px;font-weight:700;color:{theme.INK};font-variant-numeric:tabular-nums;">DIS {fmt(hero_report.get('overall_dis'))}</span>
                        {perf_badge(hero_perf)}
                    </div>
                    <div style="font-size:14px;color:{theme.TEXT};margin-top:10px;line-height:1.5;">
                        {hero_report.get('recommendation', '')}
                    </div>
                    {older_confirmed_html}
                </div>
                """,
                unsafe_allow_html=True,
            )
        with hero_right:
            st.markdown(
                f"""
                <div class="dg-card" style="height:100%;margin-bottom:0;">
                    <div style="font-size:12px;font-weight:600;text-transform:uppercase;letter-spacing:0.04em;color:{theme.MUTED};margin-bottom:8px;">
                        Drift Types · {hero_bid}
                    </div>
                    <div style="display:flex;justify-content:space-between;align-items:center;padding:5px 0;border-bottom:1px solid #F1F5F9;font-size:13px;color:{theme.TEXT};"><span>Data drift</span>{_drift_type_pill(dt.get('data_drift'))}</div>
                    <div style="display:flex;justify-content:space-between;align-items:center;padding:5px 0;border-bottom:1px solid #F1F5F9;font-size:13px;color:{theme.TEXT};"><span>Prediction drift</span>{_drift_type_pill(dt.get('prediction_drift'))}</div>
                    <div style="display:flex;justify-content:space-between;align-items:center;padding:5px 0;border-bottom:1px solid #F1F5F9;font-size:13px;color:{theme.TEXT};"><span>Concept drift</span>{_drift_type_pill(dt.get('concept_drift_suspected'))}</div>
                    <div style="display:flex;justify-content:space-between;align-items:center;padding:5px 0;font-size:13px;color:{theme.TEXT};"><span>Confirmed degradation</span>{_drift_type_pill(dt.get('confirmed_degradation'))}</div>
                </div>
                """,
                unsafe_allow_html=True,
            )
        st.markdown("<div style='height:14px'></div>", unsafe_allow_html=True)
    else:
        empty_state(
            "NO ANALYSES",
            "No analysed production batches yet",
            "Upload production batches and run an analysis in Dataset Management to populate the overview.",
        )

    # 2. KPI Row (5 equal cards)
    total_prod_customers = sum(b.get("row_count", 0) for b in batches)
    k = data["kpis"]
    drifted = hero_report.get("drifting_features_count") if hero_report else None
    sig = hero_report.get("significant_drift_count") if hero_report else 0
    active_alerts = sum(1 for b in analysed_batches if (b.get("latest_analysis") or {}).get("alert_type"))
    cust_sub = f"{len(batches)} production batches (excl. baseline)"
    if hidden_count and hide_test_batches():
        cust_sub += f" · {hidden_count} test hidden"

    champ_val = f"v{champ['version']}" if champ else "—"
    champ_sub = (
        f"AUC {fmt(champ.get('roc_auc'))} · {champ.get('algorithm', 'XGBoost')}"
        if champ
        else "No champion model"
    )

    c = st.columns(5)
    kpi_card(
        c[0],
        "Customers Monitored",
        f"{total_prod_customers:,}",
        cust_sub,
        tone="primary",
    )
    kpi_card(
        c[1],
        "Batches Analysed",
        f"{len(analysed_batches)} / {len(batches)}",
        "production batches",
        tone="primary",
    )
    kpi_card(
        c[2],
        "Drifted Features",
        "—" if drifted is None else f"{drifted} / {k['features_monitored']}",
        f"{sig} high severity ({hero_meta['batch_id']})" if (sig and hero_meta) else "within noise floor",
        tone="high" if drifted else "low",
        help=theme.HELP_TEXTS["d"],
    )
    kpi_card(
        c[3],
        "Active Alerts",
        str(active_alerts),
        "latest batches with alert",
        tone="critical" if active_alerts else "low",
    )
    kpi_card(
        c[4],
        "Champion Model",
        champ_val,
        champ_sub,
        tone="primary",
    )

    info_callout(
        "info",
        "<b>Drift is not degradation.</b> DIS ranks how consequential an input shift could be for credit scoring; "
        "performance degradation is confirmed only when actual loan default outcomes arrive.",
    )

    # 3. Main Row: DIS Trend (with labelled shaded threshold bands) + Features Drifting per Batch
    if trend:
        left, right = st.columns(2)
        with left:
            fig = go.Figure()
            fig.add_hrect(
                y0=thresholds[1],
                y1=1.05,
                fillcolor=theme.RISK_COLORS["HIGH RISK"][1],
                line_width=0,
                layer="below",
                annotation_text=f"High ≥ {thresholds[1]:.2f}",
                annotation_position="top right",
                annotation_font={"size": 11, "color": theme.RISK_COLORS["HIGH RISK"][0]},
            )
            fig.add_hrect(
                y0=thresholds[0],
                y1=thresholds[1],
                fillcolor=theme.RISK_COLORS["MEDIUM RISK"][1],
                line_width=0,
                layer="below",
                annotation_text=f"Moderate ≥ {thresholds[0]:.2f}",
                annotation_position="top right",
                annotation_font={"size": 11, "color": theme.RISK_COLORS["MEDIUM RISK"][0]},
            )
            fig.add_trace(
                go.Scatter(
                    x=[t["batch_id"] for t in trend],
                    y=[t["overall_dis"] for t in trend],
                    mode="lines+markers+text",
                    line={"color": theme.DIS_COLOR, "width": 2.5},
                    text=[fmt(t["overall_dis"], ".2f") for t in trend],
                    textposition="top center",
                    cliponaxis=False,
                    name="Overall DIS",
                    marker={
                        "size": 10,
                        "color": [theme.risk_color(t["risk_category"])[0] for t in trend],
                        "line": {"color": "white", "width": 2},
                    },
                    customdata=[[t["risk_category"], format_date(t["batch_date"])] for t in trend],
                    hovertemplate="%{x} (%{customdata[1]})<br>DIS %{y:.3f} · %{customdata[0]}<extra></extra>",
                )
            )
            fig.update_yaxes(range=[0, 1.05], title="Overall DIS")
            chart(layout(fig, 340, "DIS Trend Across Batches", legend=False), key="ov_dis_trend")
        with right:
            fig = go.Figure()
            fig.add_trace(
                go.Bar(
                    x=[t["batch_id"] for t in trend],
                    y=[
                        t["drifting_features_count"] - t["significant_drift_count"]
                        for t in trend
                    ],
                    name="Moderate",
                    marker_color=theme.SEVERITY_COLORS["moderate"][0],
                )
            )
            fig.add_trace(
                go.Bar(
                    x=[t["batch_id"] for t in trend],
                    y=[t["significant_drift_count"] for t in trend],
                    name="High",
                    marker_color=theme.RISK_COLORS["CRITICAL RISK"][0],
                )
            )
            fig.update_layout(barmode="stack")
            fig.update_yaxes(title="Drifting features", dtick=1)
            chart(layout(fig, 340, "Features Drifting per Batch"), key="ov_feat_trend")

    # 4. Bottom Row: Top 5 Features by DIS (evidence_row) + Recent Alerts table
    bot_left, bot_right = st.columns(2)
    with bot_left:
        section(
            f"Top 5 Features by DIS ({hero_meta['batch_id']})" if hero_meta else "Top 5 Features by DIS",
            "Mini bars: D (blue), FI (violet), S (teal) → DIS",
        )
        if hero_report and hero_report.get("feature_details"):
            top5 = sorted(
                hero_report["feature_details"], key=lambda f: f.get("dis") or 0.0, reverse=True
            )[:5]
            rows_html = "".join(
                evidence_row(
                    f["label"],
                    f.get("d") or 0.0,
                    f.get("fi") or 0.0,
                    f.get("s") or 0.0,
                    f.get("dis") or 0.0,
                    f.get("severity"),
                )
                for f in top5
            )
            st.markdown(f'<div class="dg-card">{rows_html}</div>', unsafe_allow_html=True)
        else:
            empty_state("NO FEATURES", "No feature scores yet", "Run an analysis to rank features by DIS.")

    with bot_right:
        section("Recent Alerts", "Latest monitoring jobs that raised a warning or degradation alert")
        if recent_alerts:
            alert_df = pd.DataFrame(
                [
                    {
                        "Time": format_timestamp(a.get("alert_created_at")),
                        "Batch": a.get("batch_id"),
                        "Type": a.get("alert_type"),
                        "Level": (a.get("alert_level") or "").upper(),
                    }
                    for a in recent_alerts[:8]
                ]
            )
            st.dataframe(alert_df, hide_index=True, width="stretch", height=240)
        else:
            empty_state("NO ALERTS", "No alerts raised", "All analysed production batches are within normal thresholds.")

    # 5. Secondary Diagnostics (Heatmap, Distributions, Default Rates)
    with st.expander("Detailed Diagnostics: Severity Matrix, Distributions & Default Rates", expanded=False):
        tab_hm, tab_dist, tab_rates = st.tabs(
            ["Severity Heatmap", "Feature Distributions", "Default Rate Surveillance"]
        )
        with tab_hm:
            if trend:
                hm = data["heatmap"]
                keep_idx = [i for i, bid in enumerate(hm["batches"]) if bid in visible_ids]
                hm_batches = [hm["batches"][i] for i in keep_idx]
                hm_d = [[row[i] for i in keep_idx] for row in hm["d"]]
                fig = go.Figure(
                    go.Heatmap(
                        z=hm_d,
                        x=hm_batches,
                        y=hm["features"],
                        zmin=0,
                        zmax=1,
                        colorscale=[[0, "#F8FAFC"], [0.15, "#DBEAFE"], [0.5, "#60A5FA"], [1, theme.DIS_COLOR]],
                        text=[[fmt(v, ".2f") for v in row] for row in hm_d],
                        texttemplate="%{text}",
                        hovertemplate="%{y} · %{x}<br>D = %{z:.2f}<extra></extra>",
                        colorbar={"title": "D"},
                    )
                )
                fig.update_yaxes(autorange="reversed")
                chart(layout(fig, 420, "Normalised Drift Severity (D) Matrix", legend=False), key="ov_hm")
        with tab_dist:
            dists = _filter_distributions(data["distributions"], visible_ids)
            labels = {
                "debt_to_income": "Debt-to-Income (DTI)",
                "monthly_income": "Monthly Income",
                "credit_score": "Credit Score",
                "outstanding_loan_amount": "Outstanding Loans",
                "credit_limit": "Credit Limit",
                "fd_balance": "FD Balance",
                "employment_type": "Employment Type",
            }
            pick = st.selectbox("Financial attribute", list(labels), format_func=labels.get, key="ov_attr")
            if pick:
                chart(
                    distribution_figure(dists.get(pick), f"{labels[pick]}: Baseline vs Production", 340),
                    key="ov_dist",
                )
        with tab_rates:
            rates = [
                r
                for r in data["default_rates"]
                if r["population"] == "Baseline 2020"
                or not (hide_test_batches() and is_test_batch(r["population"]))
            ]
            if rates:
                fig = go.Figure()
                names = [r["population"] for r in rates]
                actual = [r["actual_default_rate"] for r in rates]
                fig.add_trace(
                    go.Bar(
                        x=names,
                        y=actual,
                        name="Actual Default Rate",
                        marker_color=[theme.BASELINE_COLOR] + [theme.DIS_COLOR] * (len(rates) - 1),
                        text=[fmt(v, ".1%", "Unknown – labels pending") for v in actual],
                        textposition="outside",
                        cliponaxis=False,
                    )
                )
                fig.add_trace(
                    go.Bar(
                        x=names,
                        y=[r["predicted_default_rate"] for r in rates],
                        name="Predicted Default Rate",
                        marker_color=theme.D_COLOR,
                        text=[fmt(r["predicted_default_rate"], ".1%") for r in rates],
                        textposition="outside",
                        cliponaxis=False,
                    )
                )
                fig.update_layout(barmode="group")
                fig.update_yaxes(tickformat=".0%", title="Default Rate")
                chart(layout(fig, 340, "Actual vs Predicted Default Rate"), key="ov_rates")


def _filter_distributions(dists: dict, visible_ids: set[str]) -> dict:
    if not hide_test_batches():
        return dists
    out = {}
    for col, payload in (dists or {}).items():
        if not payload or not payload.get("series"):
            out[col] = payload
            continue
        series = {
            k: v
            for k, v in payload["series"].items()
            if k == "Baseline 2020" or k in visible_ids
        }
        out[col] = {**payload, "series": series}
    return out


def _thresholds(data: dict) -> tuple[float, float]:
    t = data["thresholds"]
    return t["batch_dis_moderate"], t["batch_dis_high"]
